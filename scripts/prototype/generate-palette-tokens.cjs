/* 组装一套配色的完整基础色（状态四键缺省取全局默认，§1）。 */
function baseOf(palette, mode) {
  const state = palette[mode];
  return Object.assign({}, state, {
    danger: state.danger || data.statusDefaults[mode].danger,
    success: state.success || data.statusDefaults[mode].success,
    warning: state.warning || data.statusDefaults[mode].warning,
    info: state.info || data.statusDefaults[mode].info
  });
}

