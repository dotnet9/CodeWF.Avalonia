/* ── 生成 CSS 块 ──────────────────────────────────────────────────────── */
function cssBlock(mode, paletteKey, vars) {
  const lines = ['  color-scheme:' + mode + ';'];
  for (const [name, value] of Object.entries(vars)) lines.push('  --' + name + ':' + value + ';');
  return ':root[data-theme=' + mode + ']' + (paletteKey ? '[data-palette=' + paletteKey + ']' : '') + ' {\n'
    + lines.join('\n') + '\n}';
}

/* 一套配色 × 一个明暗态的完整变量集：先规则语义长名（deriveVars 原样投影），再短名映射层。 */
function varsOf(palette, mode) {
  const base = baseOf(palette, mode);
  const derived = Rules.deriveVars(base, mode, data.derivation[mode]);
  const vars = {};
  Object.assign(vars, derived); // 长名词汇：--paper/--panel/--fg/--muted/--border/--hover/--selected/--accent/--accent-soft/--selection/--primary/--primary-hover/--primary-pressed/--danger…
  for (const [shortName, derivedKey] of SHORT_VAR_MAP) {
    if (!(derivedKey in derived)) throw new Error('短名映射指向不存在的派生键: ' + shortName + ' -> ' + derivedKey);
    vars[shortName.replace(/^--/, '')] = derived[derivedKey];
  }
  return vars;
}

const fallbackPalette = data.palettes[data.default];
if (!fallbackPalette) throw new Error('附录 A default 指向不存在的配色: ' + data.default);

const blocks = [];
// 回退块（= 默认配色 indigo 派生）：html 只带 data-theme、data-palette 缺失或未知时兜底。
for (const mode of MODES) blocks.push(cssBlock(mode, null, varsOf(fallbackPalette, mode)));
// 8 套 × 明暗。
for (const [key, palette] of Object.entries(data.palettes)) {
  for (const mode of MODES) blocks.push(cssBlock(mode, key, varsOf(palette, mode)));
}

