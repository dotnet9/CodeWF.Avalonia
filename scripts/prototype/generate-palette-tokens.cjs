/* ── --check：产物新鲜度 + 三项静态自检，不落盘 ────────────────────────── */
function checkJsSyntax() {
  const jsFiles = ['assets/palette-rules.js', 'assets/palette-meta.js', 'assets/interact.js', 'assets/studio.js',
    'assets/catalog-gallery.js', 'assets/catalog-data.js', 'assets/property-panel.js', 'assets/control-examples.js',
    'assets/catalog-properties.js'];
  for (const file of jsFiles) {
    const source = fs.readFileSync(path.join(prototypeRoot, file), 'utf8');
    try { new vm.Script(source, { filename: file }); } catch (error) {
      return [file + ': ' + error.message];
    }
  }
  return [];
}
function checkVarCoverage() {
  // 定义来源：生成的 palette-tokens.css（内存值）+ 原型内其余静态定义（模板 head / 各 css / JS setProperty）。
  const cssSources = ['assets/studio.css', 'assets/catalog-gallery.css', 'assets/property-panel.css',
    'assets/property-studio.css', 'index.template.html', 'property-panel.template.html'];
  const defined = new Set();
  for (const line of paletteTokensCss.split('\n')) {
    const m = line.match(/^\s*(--[A-Za-z0-9-]+)\s*:/);
    if (m) defined.add(m[1]);
  }
  const consumers = [];
  for (const file of cssSources) {
    const text = fs.readFileSync(path.join(prototypeRoot, file), 'utf8');
    for (const m of text.matchAll(/(--[A-Za-z0-9-]+)\s*:/g)) defined.add(m[1]);
    consumers.push([file, text]);
  }
  for (const file of ['assets/interact.js', 'assets/studio.js', 'assets/catalog-gallery.js', 'assets/control-examples.js', 'assets/property-panel.js']) {
    consumers.push([file, fs.readFileSync(path.join(prototypeRoot, file), 'utf8')]);
  }
  // JS 里 setProperty / style 内联动态定义的变量也算已定义。
  for (const [, text] of consumers) {
    for (const m of text.matchAll(/setProperty\(\s*['"](--[A-Za-z0-9-]+)['"]/g)) defined.add(m[1]);
  }
  const problems = [];
  for (const [file, text] of consumers) {
    for (const m of text.matchAll(/var\(\s*(--[A-Za-z0-9-]+)\s*(,([^()]*))?\)/g)) {
      const name = m[1];
      const hasFallback = m[2] !== undefined;
      if (!defined.has(name) && !hasFallback) problems.push(file + ' 消费了未定义变量 ' + name);
    }
  }
  return problems;
}
function checkLocalResources() {
  const problems = [];
  for (const template of ['index.template.html', 'property-panel.template.html']) {
    const text = fs.readFileSync(path.join(prototypeRoot, template), 'utf8');
    for (const m of text.matchAll(/\b(?:href|src)\s*=\s*["']([^"']+)["']/g)) {
      const ref = m[1];
      if (/^(https?:|data:|#|\/\/)/.test(ref)) continue;
      const file = ref.split(/[?#]/)[0];
      if (!fs.existsSync(path.join(prototypeRoot, file))) problems.push(template + ' 引用的本地资源不存在: ' + ref);
    }
  }
  return problems;
}

if (args.includes('--check')) {
  const stale = outputs.filter(([file, value]) => !isFresh(file, value)).map(([file]) => file);
  const failures = [].concat(checkJsSyntax(), checkVarCoverage(), checkLocalResources());
  if (stale.length) { console.error('产物过期（请运行 node scripts/prototype/generate-palette-tokens.cjs）: ' + stale.join(', ')); process.exitCode = 1; }
  if (failures.length) { failures.forEach(message => console.error('  ✗ ' + message)); process.exitCode = 1; }
  if (!stale.length && !failures.length) console.log('--check 通过：JS 语法可解析；var() 消费均有定义；本地资源齐全。');
  process.exit(process.exitCode || 0);
}

