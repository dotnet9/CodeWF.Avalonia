/* ── 生成 palette-meta.js（UI 元数据 + 色卡 + 别名） ───────────────────── */
function swatchOf(palette) {
  // 色卡 = 8 个独立小圆圈的颜色数组（每色一圈，横向排一行）：
  // paper/surface/ink/accent/danger/success/warning/info 浅色态（与 Vex 侧同规格）。
  const base = baseOf(palette, 'light');
  return [base.paper, base.surface, base.ink, base.accent, base.danger, base.success, base.warning, base.info];
}

