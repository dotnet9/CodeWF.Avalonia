// 从《配色与排版令牌规则.md》附录 A 与 Tokens 模板布局生成 C# 令牌代码。
// 用法：node scripts/generate/generate-studio-cs.cjs
// 产物：StudioTokens.g.cs（字典填充）/ StudioPalettes.g.cs（9 套数据）。勿手改产物。
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');

const doc = fs.readFileSync(path.join(root, 'docs/配色与排版令牌规则.md'), 'utf8');
const appendix = doc.slice(doc.indexOf('## 附录 A'));
const data = JSON.parse(appendix.match(/```json\s*([\s\S]*?)```/)[1]);
const layout = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens-layout.json'), 'utf8'));

const outDir = path.join(root, 'src/Controls/CodeWF.Avalonia.Controls/Themes/Studio');
const lines = [];
lines.push(`// <auto-generated>由 scripts/generate/generate-studio-cs.cjs 从《配色与排版令牌规则.md》附录 A 与 Tokens 模板布局生成（ruleVersion ${data.ruleVersion}）。勿手改。</auto-generated>`);
lines.push(`using Avalonia.Media;`);
lines.push(`using Avalonia;`);
lines.push(`namespace CodeWF.Avalonia.Controls.Themes;`);
lines.push(`/// <summary>按引擎基色填充令牌字典（键集与令牌模板一一对应）。</summary>`);
lines.push(`public static partial class StudioTokens`);
lines.push(`{`);
lines.push(`  public static void Fill(global::Avalonia.Controls.ResourceDictionary d, System.Collections.Generic.IReadOnlyDictionary<string, Color> v)`);
lines.push(`  {`);
for (const e of layout) {
  const K = JSON.stringify(e.key);
  if (e.tag === 'Color') {
    lines.push(`    d[${K}] = v[${K}];`);
  } else if (e.tag === 'SolidColorBrush') {
    const colorAttr = (e.attrs.match(/Color="([^"]+)"/) || [])[1];
    const inner = (e.content.match(/<Color>([^<]+)<\/Color>/) || [])[1];
    const raw = colorAttr || inner;
    if (!raw) { lines.push(`    d[${K}] = Brushes.Transparent;`); continue; }
    const sr = raw.match(/\{StaticResource ([^}]+)\}/);
    if (sr) lines.push(`    d[${K}] = AsBrush(v, d, ${JSON.stringify(sr[1])});`);
    else lines.push(`    d[${K}] = new SolidColorBrush(Color.Parse("${raw}"));`);
  } else if (e.tag === 'StaticResource') {
    const rk = (e.attrs.match(/ResourceKey="([^"]+)"/) || [])[1];
    lines.push(`    Copy(d, ${K}, ${JSON.stringify(rk)});`);
  } else if (e.tag === 'LinearGradientBrush') {
    const stops = [...e.content.matchAll(/<GradientStop[^>]*Color="([^"]+)"[^>]*Offset="([^"]+)"/g)].map(m => {
      const sr = m[1].match(/\{StaticResource ([^}]+)\}/);
      const expr = sr ? `AsColor(v, ${JSON.stringify(sr[1])})` : `Color.Parse("${m[1]}")`;
      return `new GradientStop(${expr}, ${m[2]})`;
    }).join(', ');
    lines.push(`    d[${K}] = new LinearGradientBrush { StartPoint = new RelativePoint(0, 0, RelativeUnit.Relative), EndPoint = new RelativePoint(1, 1, RelativeUnit.Relative), GradientStops = { ${stops} } };`);
  } else if (e.tag === 'x:String' || e.tag.endsWith('String')) {
    lines.push(`    d[${K}] = "${e.content.replace(/"/g, '\\"')}";`);
  }
}
lines.push(`  }`);
lines.push(``);
lines.push(`  private static Color AsColor(System.Collections.Generic.IReadOnlyDictionary<string, Color> v, string key)`);
lines.push(`    => v.TryGetValue(key, out var color) ? color : throw new System.Collections.Generic.KeyNotFoundException("令牌基色缺失: " + key);`);
lines.push(`  private static SolidColorBrush AsBrush(System.Collections.Generic.IReadOnlyDictionary<string, Color> v, global::Avalonia.Controls.ResourceDictionary d, string key)`);
lines.push(`    => v.TryGetValue(key, out var color) ? new SolidColorBrush(color) : d.TryGetValue(key, out var value) && value is SolidColorBrush brush ? brush : new SolidColorBrush(Colors.Transparent);`);
lines.push(`  private static void Copy(global::Avalonia.Controls.ResourceDictionary d, string key, string sourceKey)`);
lines.push(`  {`);
lines.push(`    if (d.TryGetValue(sourceKey, out var value)) d[key] = value;`);
lines.push(`  }`);
lines.push(`}`);
fs.writeFileSync(path.join(outDir, 'StudioTokens.g.cs'), lines.join('\n') + '\n');

const pal = [];
for (const [key, p] of Object.entries(data.palettes)) {
  pal.push(`    new StudioPaletteDefinition("${key}", "${p.label}", "${p.en}", "${p.note}", ${p.recommended ? 'true' : 'false'},
      new StudioBaseColors("${p.light.paper}", "${p.light.surface}", "${p.light.ink}", "${p.light.accent}"),
      new StudioBaseColors("${p.dark.paper}", "${p.dark.surface}", "${p.dark.ink}", "${p.dark.accent}")),`);
}
const out2 = [];
out2.push(`// <auto-generated>由 scripts/generate/generate-studio-cs.cjs 生成（ruleVersion ${data.ruleVersion}）。勿手改。</auto-generated>`);
out2.push(`namespace CodeWF.Avalonia.Controls.Themes;`);
out2.push(`/// <summary>内置九套高对比配色（编写层 4 色 × 双明暗）。</summary>`);
out2.push(`public sealed record StudioPaletteDefinition(string Key, string Name, string EnglishName, string Note, bool Recommended, StudioBaseColors Light, StudioBaseColors Dark);`);
out2.push(`public sealed record StudioBaseColors(string Paper, string Surface, string Ink, string Accent);`);
out2.push(`public static partial class StudioPalettes`);
out2.push(`{`);
out2.push(`  public static string DefaultKey { get; } = ${JSON.stringify(data.default)};`);
out2.push(`  public static System.Collections.Generic.IReadOnlyList<StudioPaletteDefinition> All { get; } = new StudioPaletteDefinition[]`);
out2.push(`  {`);
out2.push(pal.join('\n'));
out2.push(`  };`);
out2.push(`}`);
fs.writeFileSync(path.join(outDir, 'StudioPalettes.g.cs'), out2.join('\n') + '\n');
console.log('StudioTokens.g.cs 与 StudioPalettes.g.cs 已生成（ruleVersion ' + data.ruleVersion + '）');
